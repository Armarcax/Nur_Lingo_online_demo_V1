const AUDIO_DIRS: Record<string, string> = {
  hy: 'hy_Ani',
  en: 'en_female',
  ru: 'ru_female',
};

// ─── CACHE ──────────────────────────────────────────────────────────
const resolverCache: Record<string, OfflineAudioResult | null> = {};

function isValidAudioKey(key: string): boolean {
  if (!key || key.length < 2) return false;
  return true;
}

// ─── RESOLVE CANONICAL ID ──────────────────────────────────────────
function resolveCanonicalAudioId(key: string): string | null {
  if (!key || !isValidAudioKey(key)) return null;
  
  // ✅ 1. Check PROMPT_ANSWER_MAP first (ONLY prompts and answers)
  if (PROMPT_ANSWER_MAP[key]) {
    return PROMPT_ANSWER_MAP[key];
  }
  
  // 2. Direct mapping from EXERCISE_TO_AUDIO
  let audioId = EXERCISE_TO_AUDIO[key];
  if (audioId) {
    if (audioId.startsWith('greet_')) {
      const numericId = GREET_TO_NUM[audioId];
      if (numericId) return numericId;
    }
    if (/^\d{6}$/.test(audioId)) return audioId;
    return audioId;
  }
  
  // 3. Try with _answer or _prompt suffix
  for (const suffix of ['_answer', '_prompt']) {
    const suffixKey = `${key}${suffix}`;
    audioId = EXERCISE_TO_AUDIO[suffixKey];
    if (audioId) {
      if (audioId.startsWith('greet_')) {
        const numericId = GREET_TO_NUM[audioId];
        if (numericId) return numericId;
      }
      if (/^\d{6}$/.test(audioId)) return audioId;
      return audioId;
    }
  }
  
  // 4. Try with language prefix
  for (const lang of ['hy', 'en', 'ru']) {
    const langKey = `${lang}_${key}`;
    audioId = EXERCISE_TO_AUDIO[langKey];
    if (audioId) {
      if (audioId.startsWith('greet_')) {
        const numericId = GREET_TO_NUM[audioId];
        if (numericId) return numericId;
      }
      if (/^\d{6}$/.test(audioId)) return audioId;
      return audioId;
    }
  }
  
  // 5. Try lesson pattern matching
  const lessonMatch = key.match(/^(w\d+_l\d+)_/);
  if (lessonMatch) {
    const prefix = lessonMatch[1];
    for (const [mapKey, mapValue] of Object.entries(EXERCISE_TO_AUDIO)) {
      if (mapKey.startsWith(prefix)) {
        if (/^\d{6}$/.test(mapValue)) return mapValue;
        if (mapValue.startsWith('greet_')) {
          const numericId = GREET_TO_NUM[mapValue];
          if (numericId) return numericId;
        }
        return mapValue;
      }
    }
  }
  
  // 6. Try numeric extraction
  const numberOnly = key.replace(/[^0-9]/g, '');
  if (numberOnly && numberOnly.length > 0) {
    const padded = numberOnly.padStart(6, '0');
    return padded;
  }
  
  return null;
}

// ─── GET AUDIO URL ──────────────────────────────────────────────────
function getAudioUrl(canonicalId: string, language: 'hy' | 'en' | 'ru'): string | null {
  if (!canonicalId) return null;
  
  const dir = AUDIO_DIRS[language] || AUDIO_DIRS.hy;
  
  if (/^\d{6}$/.test(canonicalId)) {
    return `/audio/offline/${dir}/${canonicalId}.mp3`;
  }
  
  const audioId = EXERCISE_TO_AUDIO[canonicalId];
  if (audioId) {
    if (/^\d{6}$/.test(audioId)) {
      return `/audio/offline/${dir}/${audioId}.mp3`;
    }
    if (audioId.startsWith('greet_')) {
      const numericId = GREET_TO_NUM[audioId];
      if (numericId) {
        return `/audio/offline/${dir}/${numericId}.mp3`;
      }
    }
  }
  
  return null;
}

// ─── MAIN RESOLVE FUNCTIONS ────────────────────────────────────────

export function resolveExerciseAudio(
  exerciseId: string,
  language: 'hy' | 'en' | 'ru' = 'hy'
): OfflineAudioResult | null {
  if (!exerciseId) return null;
  
  const cacheKey = `${exerciseId}_${language}`;
  if (resolverCache[cacheKey] !== undefined) {
    return resolverCache[cacheKey];
  }
  
  const canonicalId = resolveCanonicalAudioId(exerciseId);
  if (canonicalId) {
    const url = getAudioUrl(canonicalId, language);
    if (url) {
      const result = { url, key: canonicalId, source: 'lesson' as const };
      resolverCache[cacheKey] = result;
      return result;
    }
  }
  
  // Numeric fallback
  const numberOnly = exerciseId.replace(/[^0-9]/g, '');
  if (numberOnly && numberOnly.length > 0) {
    const paddedNum = numberOnly.padStart(6, '0');
    const dir = AUDIO_DIRS[language] || AUDIO_DIRS.hy;
    const url = `/audio/offline/${dir}/${paddedNum}.mp3`;
    const result = { url, key: paddedNum, source: 'fallback' as const };
    resolverCache[cacheKey] = result;
    return result;
  }
  
  resolverCache[cacheKey] = null;
  return null;
}

export function resolveOfflineAudio(
  key: string,
  language: 'hy' | 'en' | 'ru' = 'hy'
): OfflineAudioResult | null {
  if (!key || !isValidAudioKey(key)) return null;
  return resolveExerciseAudio(key, language);
}

export function hasOfflineAudio(key: string, language: 'hy' | 'en' | 'ru' = 'hy'): boolean {
  return resolveOfflineAudio(key, language) !== null;
}

export function getOfflineAudioUrl(
  key: string,
  language: 'hy' | 'en' | 'ru' = 'hy'
): string | null {
  const result = resolveOfflineAudio(key, language);
  return result ? result.url : null;
}

export function clearOfflineAudioCache(): void {
  for (const key of Object.keys(resolverCache)) {
    delete resolverCache[key];
  }
}

