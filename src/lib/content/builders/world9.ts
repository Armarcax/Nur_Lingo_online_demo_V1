    id,
    worldId: "w9",
    slug,
    difficulty: "B1",
    title: { en: enT, hy: hyT, ru: ruT },
    concept: { en: `Business topics: ${enT}`, hy: `Բիզնես թեմա՝ ${hyT}`, ru: `Бизнес тема: ${ruT}` },
