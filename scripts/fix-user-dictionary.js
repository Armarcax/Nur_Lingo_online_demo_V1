// ─── ԳԼԽԱՎՈՐ ՖՈՒՆԿՑԻԱ ──────────────────────────────────────────

function fixUserDictionary() {
  const filePath = path.join(process.cwd(), 'data/dictionaries/user-dictionary.json');
  
  if (!fs.existsSync(filePath)) {
    console.log('❌ user-dictionary.json ֆայլը չի գտնվել');
    return;
  }

  const content = fs.readFileSync(filePath, 'utf-8');
  const entries = JSON.parse(content);

  let fixedCount = 0;
  const fixedEntries = entries.map(entry => {
    const ru = entry.ru;
    const translation = translations[ru];
    
    if (translation) {
      fixedCount++;
      return {
        ...entry,
        hy: translation.hy,
        en: translation.en,
        ru: ru,
      };
    }
    return entry;
  });

  // Պահպանել նոր ֆայլը
  const newFilePath = path.join(process.cwd(), 'data/dictionaries/user-dictionary-fixed.json');
  fs.writeFileSync(newFilePath, JSON.stringify(fixedEntries, null, 2));
  
  console.log(`✅ Ֆիքսված բառարանը պահպանվեց: ${newFilePath}`);
  console.log(`📊 Ընդհանուր: ${entries.length} բառ`);
  console.log(`✅ Ֆիքսված: ${fixedCount} բառ`);
  console.log(`⚠️  Չֆիքսված: ${entries.length - fixedCount} բառ (հնարավոր է նոր ռուսերեն բառեր)`);
}

// ─── ԳՈՐԾԱՐԿԵԼ ──────────────────────────────────────────────────────

fixUserDictionary();